/* HTTP response header format string.*/
#define HTTP_BINARY_HEADER_FORMAT_STRING      "HTTP/1.1 200 OK\r\n" \
                                              "Date: Tue, 19 May 2020 23:59:59 GMT\r\n" \
                                              "Content-Type: application/octet-stream\r\n" \
                                              "Content-Length: %lu \r\n\r\n"

/* HTTP response header buffer. */
static CHAR http_binary_header_string[] = { HTTP_BINARY_HEADER_FORMAT_STRING "              " };

/* Message to be sent as a response. */
static const UCHAR gMsg[] = { "Hello world!\n" };

/* Receive buffer. */
static UCHAR gReceiveBuffer[256];



/* ========================================================================== */
/*                          Function Definitions                              */
/* ========================================================================== */

int netxduo_cpsw_main(ULONG arg)
{
    Enet_Type enetType;
    uint32_t instId;
    Enet_Handle hEnet;
    ULONG ipAddr;
    ULONG netMask;
    ULONG record_rem_size;
    ULONG append_size;
    ULONG record_size;
    ULONG total_rem_size;
    Enet_MacPort macPort;
    ULONG actual_status;
    NX_PACKET *send_packet;
    NX_PACKET *receive_packet;
    uint32_t rxChCnt;
    uint32_t txChCnt;
    const uint32_t *rxChIds;
    const uint32_t *txChIds;
    nx_enet_drv_rx_ch_hndl_t rxChs[ENET_SYSCFG_RX_FLOWS_NUM];
    nx_enet_drv_tx_ch_hndl_t txChs[ENET_SYSCFG_TX_CHANNELS_NUM];
    const NX_SECURE_TLS_CRYPTO *p_ciphers;
    EnetApp_GetMacAddrOutArgs outArgs;
    UINT cur_data_offset;
    bool isLinked;
    ULONG bytes;
    UINT status;
    int32_t res;

    Drivers_open();
    Board_driversOpen();

    DebugP_log("==================================\r\n");
    DebugP_log("   CPSW NETXDUO HTTPS BENCHMARK   \r\n");
    DebugP_log("==================================\r\n");


    EnetApp_getEnetInstInfo(CONFIG_ENET_CPSW0, &enetType, &instId);

    EnetAppUtils_enableClocks(enetType, instId);

    EnetApp_driverInit();
    res = EnetApp_driverOpen(enetType, instId);
    DebugP_assert(res == ENET_SOK);


    /* Initialize the NetX system.  */
    nx_system_initialize();


    /* Create a packet pool.  */
    status = nx_packet_pool_create(&gUserPacketPool, "User Packet Pool", PACKET_SIZE, &gUserPoolMem[0], USER_POOL_SIZE);
    EnetAppUtils_assert(status == NX_SUCCESS);

    status = nx_packet_pool_create(&gInternalPacketPool, "User Packet Pool", PACKET_SIZE, &gInternalPoolMem[0], INTERNAL_POOL_SIZE);
    EnetAppUtils_assert(status == NX_SUCCESS);


    EnetApp_addMCastEntry(enetType, instId, EnetSoc_getCoreId(), BROADCAST_MAC_ADDRESS, CPSW_ALE_ALL_PORTS_MASK);


    /* Allocate NetX Rx channel and corresponding buffers. */
    NetxEnetApp_getAllRxChIDs(&rxChIds, &rxChCnt);
    for(size_t k = 0u; k < rxChCnt; k++) {

        EnetApp_GetDmaHandleInArgs inArgs = {0};
        EnetApp_GetRxDmaHandleOutArgs outArgs;

        EnetApp_getRxDmaHandle(rxChIds[k], &inArgs, &outArgs);

        EnetAppUtils_assert(outArgs.hRxCh != NULL);
        NetxEnetDriver_allocRxCh(outArgs.hRxCh, outArgs.maxNumRxPkts, &gInternalPacketPool, &rxChs[k]);
    }

    /* Allocate NetX Tx channel and corresponding buffers. */
    NetxEnetApp_getAllTxChIDs(&txChIds, &txChCnt);
    for (size_t k = 0u; k < txChCnt; k++) {

        EnetApp_GetDmaHandleInArgs inArgs = {0};
        EnetApp_GetTxDmaHandleOutArgs outArgs;

        EnetApp_getTxDmaHandle(txChIds[k], &inArgs, &outArgs);

        EnetAppUtils_assert(outArgs.hTxCh != NULL);
        NetxEnetDriver_allocTxCh(outArgs.hTxCh, outArgs.maxNumTxPkts, &txChs[k]);
    }

    macPort = NetxEnetApp_getMacPort(0, 0);
    EnetApp_getMacAddress(rxChIds[0], &outArgs);
    NetxEnetDriver_allocIf("PRI", macPort, &outArgs.macAddr[0][0], &rxChs[0], rxChCnt, txChs, txChCnt);


    /* Wait for the link on default interface to come up. */
    hEnet = Enet_getHandle(enetType, instId);

    isLinked = false;
    while (!isLinked) {

        EnetAppUtils_print("Waiting for link up...\n");
        isLinked = EnetApp_isPortLinked(hEnet);

        tx_thread_sleep(2u * TX_TIMER_TICKS_PER_SECOND);
    }


    /* Open NetX SA2UL crypto acceleration. */
    nx_crypto_sa2ul_asym_open();
    nx_crypto_sa2ul_open();


    /* Create an IP instance.  */
    status = nx_ip_create(&gIp, "NetX IP Instance 0", IP_ADDRESS(0, 0, 0, 0), 0xFFFFFF00UL, &gInternalPacketPool, _nx_enet_driver, (void *)&gIpThreadStack[0], IP_THREAD_STACK_SIZE, 1);
    EnetAppUtils_assert(status == NX_SUCCESS);

    /* Enable ARP */
    status = nx_arp_enable(&gIp, (void *)&gIpArpThreadStack[0], IP_ARP_THREAD_STACK_SIZE);
    EnetAppUtils_assert(status == NX_SUCCESS);

    /* Enable ICMP */
    status = nxd_icmp_enable(&gIp);
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Enable UDP */
    status = nx_udp_enable(&gIp);
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Enable TCP */
    status = nx_tcp_enable(&gIp);
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Create the DHCP instance.  */
    status = nx_dhcp_create(&gDhcpClient, &gIp, "DHCP-CLIENT");
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Start the DHCP Client.  */
    status = nx_dhcp_interface_start(&gDhcpClient, 0u);
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Wait for DHCP to assign the IP address.  */
    EnetAppUtils_print("Waiting for address from DHCP server on primary interface...\n");
    do {

        /* Check for address resolution.  */
        status = nx_ip_interface_status_check(&gIp, 0u, NX_IP_ADDRESS_RESOLVED, (ULONG *) &actual_status, NX_IP_PERIODIC_RATE);

        tx_thread_sleep(TX_TIMER_TICKS_PER_SECOND);

    } while ((actual_status & NX_IP_ADDRESS_RESOLVED) != NX_IP_ADDRESS_RESOLVED);


    status = nx_ip_interface_address_get(&gIp, 0u, &ipAddr, &netMask);
    EnetAppUtils_assert(status == NX_SUCCESS);

    DebugP_log("Local Interface IP is: %lu.%lu.%lu.%lu\n", ((ipAddr >> 24u) & 0xFF), ((ipAddr >> 16u) & 0xFF), ((ipAddr >> 8u) & 0xFF), (ipAddr & 0xFF));


    /* Create a socket.  */
    status =  nx_tcp_socket_create(&gIp, &gServerSocket, "Server Socket", NX_IP_NORMAL, NX_FRAGMENT_OKAY, NX_IP_TIME_TO_LIVE, 8000, NX_NULL, NX_NULL);
    EnetAppUtils_assert(status == NX_SUCCESS);

    DebugP_log("Socket created\r\n");


    nx_secure_tls_initialize();

#if (CRYPTO_SELECTION == CRYPTO_RSA_CERT_ACCELERATED) || (CRYPTO_SELECTION == CRYPTO_ECDSA_CERT)
    p_ciphers = &sa2ul_crypto_tls_ciphers_ecc;
#else
    p_ciphers = &nx_crypto_tls_ciphers_ecc;
#endif


    /* Create a TLS session for our socket.  */
    status =  nx_secure_tls_session_create(&tls_session, p_ciphers, tls_crypto_metadata, sizeof(tls_crypto_metadata));
    EnetAppUtils_assert(status == NX_SUCCESS);

    status = nx_secure_tls_ecc_initialize(&tls_session, nx_crypto_ecc_supported_groups, nx_crypto_ecc_supported_groups_size, nx_crypto_ecc_curves);
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Set the packet reassembly buffer for this TLS session. */
    status = nx_secure_tls_session_packet_buffer_set(&tls_session, tls_packet_buffer, sizeof(tls_packet_buffer));
    EnetAppUtils_assert(status == NX_SUCCESS);

    /* Initialize an X.509 certificate and private ECC key for our TLS Session. */
#if (CRYPTO_SELECTION == CRYPTO_ECDSA_CERT)
    status = nx_secure_x509_certificate_initialize(&certificate, (UCHAR *)&self_signed_cert_der[0], sizeof(self_signed_cert_der), NX_NULL, 0, &private_key_der[0], sizeof(private_key_der), NX_SECURE_X509_KEY_TYPE_EC_DER);
    EnetAppUtils_assert(status == NX_SUCCESS);
#elif (CRYPTO_SELECTION == CRYPTO_RSA_CERT)
    status = nx_secure_x509_certificate_initialize(&certificate, (UCHAR *)&self_signed_cert_der[0], sizeof(self_signed_cert_der), NX_NULL, 0, &private_key_der[0], sizeof(private_key_der), NX_SECURE_X509_KEY_TYPE_RSA_PKCS1_DER);
    EnetAppUtils_assert(status == NX_SUCCESS);
#elif (CRYPTO_SELECTION == CRYPTO_RSA_CERT_ACCELERATED)
    status = nx_secure_x509_certificate_initialize(&certificate, (UCHAR *)&self_signed_cert_der[0], sizeof(self_signed_cert_der), NX_NULL, 0, (UCHAR *)&private_key_bigint, sizeof(private_key_bigint), NX_SECURE_X509_KEY_TYPE_USER_DEFINED_MASK);
    EnetAppUtils_assert(status == NX_SUCCESS);
#else
#error "Invalid crypto selection."
#endif

    /* Add the initialized certificate as a local identity certificate. */
    status = nx_secure_tls_local_certificate_add(&tls_session, &certificate);
    EnetAppUtils_assert(status == NX_SUCCESS);


    /* Listen on the socket.  */
    status =  nx_tcp_server_socket_listen(&gIp, SERVER_PORT, &gServerSocket, 1u, NULL);
    EnetAppUtils_assert(status == NX_SUCCESS);

    DebugP_log("Listening on port %lu\r\n", (ULONG)SERVER_PORT);


   while (1) {

       /* Accept a client TCP socket connection.  */
       do {

           status =  nx_tcp_server_socket_accept(&gServerSocket, NX_WAIT_FOREVER);
           EnetAppUtils_assert(status == NX_SUCCESS);


           /* Start the TLS Session using the connected TCP socket. */
           status = nx_secure_tls_session_start(&tls_session, &gServerSocket, NX_WAIT_FOREVER);

           if (status != NX_SUCCESS) {
               (void)nx_tcp_socket_disconnect(&gServerSocket, NX_WAIT_FOREVER);
               (void)nx_tcp_server_socket_unaccept(&gServerSocket);
               (void)nx_tcp_server_socket_relisten(&gIp, SERVER_PORT, &gServerSocket);
           }

       } while (status != NX_SUCCESS);


       /* Receive the HTTPS request. */
       status = nx_secure_tls_session_receive(&tls_session, &receive_packet, NX_WAIT_FOREVER);
       EnetAppUtils_assert(status == NX_SUCCESS);


        /* Extract the HTTP request information from the HTTPS request. */
        printf("Received data:\n");
        cur_data_offset = 0u;
        do {

            status = nx_packet_data_extract_offset(receive_packet, cur_data_offset, &gReceiveBuffer[0], sizeof(gReceiveBuffer) - 1u, &bytes);
            EnetAppUtils_assert(status == NX_SUCCESS);
            EnetAppUtils_assert(bytes < sizeof(gReceiveBuffer));

            /* Display the HTTP request data. */
            gReceiveBuffer[bytes] = '\0';
            printf("%s", &gReceiveBuffer[0]);

            cur_data_offset += bytes;

        } while (bytes == sizeof(gReceiveBuffer) - 1u);

        /* Release the packet when done with it */
        status = nx_packet_release(receive_packet);
        EnetAppUtils_assert(status == NX_SUCCESS);


        /****************************************************************************************
         * Initial HTTP request was received now transmit data back for performance measurement.
         ****************************************************************************************/

        /* Transmit 32MiB of data. */
        total_rem_size = 32u * 1024u * 1024u;
        record_size = 1000u;

        /* Allocate a TLS packet to send HTML data back to client. */
        status = nx_secure_tls_packet_allocate(&tls_session, &gUserPacketPool, &send_packet, NX_WAIT_FOREVER);
        EnetAppUtils_assert(status == NX_SUCCESS);


        /* Populate the packet with our HTTP response and HTML web page data. */
        sprintf(&http_binary_header_string[0], HTTP_BINARY_HEADER_FORMAT_STRING, (unsigned long)total_rem_size);
        status = nx_packet_data_append(send_packet, (UCHAR *)&http_binary_header_string[0], sizeof(http_binary_header_string), &gUserPacketPool, NX_WAIT_FOREVER);
        EnetAppUtils_assert(status == NX_SUCCESS);

        /* Transmit one-packet TLS records. Records can be larger (up to 16KiB) if more transmit packets are available. */
        record_rem_size = record_size - sizeof(http_binary_header_string);
        while (total_rem_size > 0) {

            while ((record_rem_size > 0u) && (total_rem_size > 0u)) {

                append_size = sizeof(gMsg) < record_rem_size ? sizeof(gMsg) : record_rem_size;
                append_size = (append_size > total_rem_size) ? total_rem_size : append_size;
                status = nx_packet_data_append(send_packet, (UCHAR *)&gMsg[0], append_size, &gUserPacketPool, NX_WAIT_FOREVER);
                EnetAppUtils_assert(status == NX_SUCCESS);

                total_rem_size -= append_size;
                record_rem_size -= append_size;
            }

            /* Send the HTTP response. */
            status = nx_secure_tls_session_send(&tls_session, send_packet, NX_WAIT_FOREVER);
            EnetAppUtils_assert(status == NX_SUCCESS);

            if (total_rem_size > 0u) {

                /* Allocate a TLS packet to send HTML data back to client. */
                status = nx_secure_tls_packet_allocate(&tls_session, &gUserPacketPool, &send_packet, NX_WAIT_FOREVER);
                EnetAppUtils_assert(status == NX_SUCCESS);

                record_rem_size = record_size;
            }
        }


        /* End the TLS session now that we have sent our HTTPS/HTML response. */
        status = nx_secure_tls_session_end(&tls_session, NX_WAIT_FOREVER);
        EnetAppUtils_assert(status == NX_SUCCESS);

        /* Check for errors to make sure the session ended cleanly! */

        /* Disconnect the TCP socket so we can be ready for the next request. */
        (void)nx_tcp_socket_disconnect(&gServerSocket, NX_WAIT_FOREVER);

        /* Unaccept the server socket.  */
        (void)nx_tcp_server_socket_unaccept(&gServerSocket);

        /* Setup server socket for listening again.  */
        status =  nx_tcp_server_socket_relisten(&gIp, SERVER_PORT, &gServerSocket);
        EnetAppUtils_assert(status == NX_SUCCESS);
    }

    return 0;
}

